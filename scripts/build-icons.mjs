// Copies the UI icons listed below out of the installed Iconify sets into
// src/lib/icons.ts, so they ship inline with the components that use them:
// no request to the Iconify API, no icons popping in late, works offline.
// Run `pnpm icons` after changing the list; `--check` (CI) fails if stale.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { format, resolveConfig } from "prettier";

const ICONS = [
  "pixelarticons:close",
  "pixelarticons:card-stack",
  "pixelarticons:card-sharp",
  "pixelarticons:folder",
  "pixelarticons:layout",
  "pixelarticons:info-box",
  "pixelarticons:search",
  "lucide:sun",
  "lucide:moon",
];

/** Drawn here, on the same 24px grid, where no set has the shape. */
const CUSTOM = {
  // A period "_" minimise: the line sits at the bottom, not the middle.
  "ui:minimize": { body: '<path fill="currentColor" d="M5 17h14v2H5z"/>', width: 24, height: 24 },
};

const OUT = "src/lib/icons.ts";
const require = createRequire(import.meta.url);

const entries = ICONS.map((name) => {
  const [prefix, icon] = name.split(":");
  const set = require(`@iconify-json/${prefix}/icons.json`);
  const data = set.icons[icon];
  if (!data) throw new Error(`${name} is not in @iconify-json/${prefix}`);
  return [name, { body: data.body, width: data.width ?? set.width ?? 16, height: data.height ?? set.height ?? 16 }];
}).concat(Object.entries(CUSTOM));

const source = `// Generated by scripts/build-icons.mjs from the installed Iconify sets. Do not edit.
// Pixelarticons (MIT) and Lucide (ISC); see their packages for the licences.

export const ICONS = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;

export type IconName = keyof typeof ICONS;
`;

const next = await format(source, { ...(await resolveConfig(OUT)), filepath: OUT });
const current = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return "";
  }
})();
if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error(`${OUT} is out of date; run pnpm icons`);
    process.exit(1);
  }
} else if (current !== next) {
  writeFileSync(OUT, next);
  console.log(`wrote ${OUT}`);
}
